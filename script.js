function changeLanguage(lang) {
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('placeholder', translations[lang][key]);
    }
  });

  const btnAr = document.getElementById('btn-ar');
  const btnEn = document.getElementById('btn-en');
  if (btnAr && btnEn) {
    if (lang === 'ar') {
      btnAr.classList.add('active');
      btnEn.classList.remove('active');
    } else {
      btnEn.classList.add('active');
      btnAr.classList.remove('active');
    }
  }

  localStorage.setItem('preferredLang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('preferredLang') || 'ar';
  changeLanguage(savedLang);

  // Modal Functionality
  document.querySelectorAll('[data-modal]').forEach(trigger => {
    trigger.addEventListener('click', () => {
      const modalId = trigger.getAttribute('data-modal');
      const modal = document.getElementById(modalId);
      if (modal) modal.classList.add('active');
    });
  });

  document.querySelectorAll('[data-close]').forEach(closer => {
    closer.addEventListener('click', () => {
      const modalId = closer.getAttribute('data-close');
      const modal = document.getElementById(modalId);
      if (modal) modal.classList.remove('active');
    });
  });

  // Lightbox Functionality
  const lightboxModal = document.getElementById('lightboxModal');
  const lightboxImg = document.getElementById('lightboxImg');
  const lightboxCaption = document.getElementById('lightboxCaption');

  document.querySelectorAll('.lightbox-trigger').forEach(item => {
    item.addEventListener('click', function() {
      const imgTag = this.querySelector('img') || this;
      const imgSrc = imgTag.getAttribute('src');
      const imgTitle = this.getAttribute('data-title') || imgTag.getAttribute('alt') || '';

      if (lightboxImg && lightboxModal) {
        lightboxImg.src = imgSrc;
        if (lightboxCaption) lightboxCaption.textContent = imgTitle;
        lightboxModal.classList.add('active');
      }
    });
  });

  // Cost Estimator WhatsApp Integration
  const estimatorForm = document.getElementById('estimatorForm');
  if (estimatorForm) {
    estimatorForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const service = document.getElementById('estService').value;
      const category = document.getElementById('estCategory').value;
      const quantity = document.getElementById('estQuantity').value || 'غير محدد';
      const city = document.getElementById('estCity').value;
      const name = document.getElementById('clientName').value;
      const phone = document.getElementById('clientPhone').value;
      const notes = document.getElementById('estNotes').value || 'لا توجد ملاحظات إضافية';

      const currentLang = document.documentElement.getAttribute('lang');
      let text = "";

      if (currentLang === 'ar') {
        text = `السلام عليكم، أود طلب عرض سعر ودراسة كميات (BOQ) من شركة نال التشيد:%0A` +
               `- نوع الخدمة: ${service}%0A` +
               `- تصنيف المشروع: ${category}%0A` +
               `- المساحة/الكمية: ${quantity}%0A` +
               `- موقع المشروع: ${city}%0A` +
               `- اسم العميل/الجهة: ${name}%0A` +
               `- رقم الجوال: ${phone}%0A` +
               `- التفاصيل والملاحظات: ${notes}`;
      } else {
        text = `Hello Nal Al Tsheed, I would like to request a quotation and BOQ review:%0A` +
               `- Service: ${service}%0A` +
               `- Category: ${category}%0A` +
               `- Quantity/Area: ${quantity}%0A` +
               `- Location: ${city}%0A` +
               `- Name/Entity: ${name}%0A` +
               `- Phone: ${phone}%0A` +
               `- Notes: ${notes}`;
      }

      const waUrl = `https://wa.me/966552880208?text=${text}`;
      window.open(waUrl, '_blank');
    });
  }
});
